age = int(input("Enter Age: "))

if age > 0:
    if age <= 12:
        print("Child")
    else:
        if age <= 19:
            print("Teenager")
        else:
            if age <= 59:
                print("Adult")
            else:
                print("Senior")
else:
    print("Invalid Age")                        



